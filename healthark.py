"""# Task
PREDICTION TASK: Will the patient be readmitted within 30/60/90 days using data from "beneficiary_data.csv" and "inpatient_claims_data.csv".

## Identify readmissions

### Subtask:
Define readmission within 30, 60, and 90 days using the claims data and beneficiary death dates.

**Reasoning**:
Sort the claims data, calculate the time difference between consecutive claims for each beneficiary, define the readmission flags based on 30, 60, and 90-day thresholds, handle claims after death dates, and shift the readmission flags to predict readmission after a claim.
"""

# Load and concatenate Inpatient and Outpatient Claims Data
inpatient_claims = pd.read_csv(folder_path+"/DE1_0_2008_to_2010_Inpatient_Claims_Sample_1.csv")
outpatient_claims = pd.read_csv(folder_path+"/DE1_0_2008_to_2010_Outpatient_Claims_Sample_1.csv", low_memory=False)

# Concatenate the dataframes
all_claims_df = pd.concat([inpatient_claims, outpatient_claims], ignore_index=True)

# Convert date columns to datetime objects
all_claims_df['CLM_FROM_DT'] = pd.to_datetime(all_claims_df['CLM_FROM_DT'], format='%Y%m%d', errors='coerce')
all_claims_df['CLM_THRU_DT'] = pd.to_datetime(all_claims_df['CLM_THRU_DT'], format='%Y%m%d', errors='coerce')

# Calculate length of stay for inpatient claims
all_claims_df['length_of_stay'] = (all_claims_df['CLM_THRU_DT'] - all_claims_df['CLM_FROM_DT']).dt.days


# Step 1: Sort the all_claims_df DataFrame
all_claims_df = all_claims_df.sort_values(by=['DESYNPUF_ID', 'CLM_FROM_DT'])

# Step 2: Calculate the time difference between consecutive claim start dates
all_claims_df['days_between_claims'] = all_claims_df.groupby('DESYNPUF_ID')['CLM_FROM_DT'].diff().dt.days

# Step 3 and 4: Create readmission flags
all_claims_df['readmit_30'] = (all_claims_df['days_between_claims'] <= 30).astype(int)
all_claims_df['readmit_60'] = (all_claims_df['days_between_claims'] <= 60).astype(int)
all_claims_df['readmit_90'] = (all_claims_df['days_between_claims'] <= 90).astype(int)

# Step 5: Handle claims after death dates
# Recreate all_years_df by concatenating the beneficiary dataframes
all_years_df = pd.concat([Benefi_08, Benefi_09, Benefi_10], ignore_index=True)
# Convert BENE_DEATH_DT to datetime
all_years_df['BENE_DEATH_DT'] = pd.to_datetime(all_years_df['BENE_DEATH_DT'], format='%d-%m-%Y', errors='coerce')

# Merge death dates into the claims data
all_claims_df = pd.merge(all_claims_df, all_years_df[['DESYNPUF_ID', 'BENE_DEATH_DT']], on='DESYNPUF_ID', how='left')

# Identify claims that occurred after the beneficiary's death date
claims_after_death = all_claims_df['CLM_FROM_DT'] > all_claims_df['BENE_DEATH_DT']

# Set readmission flags to 0 for claims after death
all_claims_df.loc[claims_after_death, ['readmit_30', 'readmit_60', 'readmit_90']] = 0

# Step 6: Shift the readmission flags to the previous row
all_claims_df['readmit_30_next'] = all_claims_df.groupby('DESYNPUF_ID')['readmit_30'].shift(-1).fillna(0).astype(int)
all_claims_df['readmit_60_next'] = all_claims_df.groupby('DESYNPUF_ID')['readmit_60'].shift(-1).fillna(0).astype(int)
all_claims_df['readmit_90_next'] = all_claims_df.groupby('DESYNPUF_ID')['readmit_90'].shift(-1).fillna(0).astype(int)

# Drop the original readmission flags as they refer to the time *before* the current claim and the death date column
all_claims_df = all_claims_df.drop(columns=['readmit_30', 'readmit_60', 'readmit_90', 'BENE_DEATH_DT'])

# Rename the shifted columns
all_claims_df = all_claims_df.rename(columns={
    'readmit_30_next': 'readmit_30',
    'readmit_60_next': 'readmit_60',
    'readmit_90_next': 'readmit_90'
})


