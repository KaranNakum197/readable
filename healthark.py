"""## Data preparation for modeling

### Subtask:
Prepare the data for machine learning by handling missing values, encoding categorical variables, and splitting the data into training and testing sets.

**Reasoning**:
Identify columns with missing values and apply imputation. Then, identify categorical columns and apply one-hot encoding. Finally, define target variables and split the data into training and testing sets.
"""

from sklearn.model_selection import train_test_split
from sklearn.preprocessing import OneHotEncoder
from sklearn.impute import SimpleImputer
from sklearn.compose import ColumnTransformer
from sklearn.pipeline import Pipeline

# 1. Identify columns with missing values
missing_info = final_features_df.isnull().sum()
missing_columns = missing_info[missing_info > 0].index.tolist()

print("Columns with missing values before imputation:", missing_columns)

# Decide on imputation strategy - using median for numerical columns and a constant for others if needed
# Based on previous steps, the new aggregated columns (total_claim_count, etc.) might have NaNs for beneficiaries
# who didn't have any claims. These should likely be imputed with 0.
# BENE_DEATH_DT has NaNs for living patients, which is expected and handled by readmission flags.

# Impute aggregated claims/drug/condition features with 0 for beneficiaries with no data
aggregated_cols = ['total_claim_count', 'total_reimbursement', 'total_beneficiary_deductible', 'average_length_of_stay',
                   'had_readmit_30', 'had_readmit_60', 'had_readmit_90', 'total_drug_exposures', 'total_days_supply',
                   'total_condition_occurrences']
for col in aggregated_cols:
    if col in final_features_df.columns:
        final_features_df[col] = final_features_df[col].fillna(0)

# Re-check missing values after imputing aggregated columns
missing_info_after_agg_impute = final_features_df.isnull().sum()
missing_columns_after_agg_impute = missing_info_after_agg_impute[missing_info_after_agg_impute > 0].index.tolist()

print("Columns with missing values after imputing aggregated features:", missing_columns_after_agg_impute)

# Handle other potential missing values if any remain in relevant columns
# For simplicity and based on previous analysis, we might not need complex imputation for other columns for this task,
# but if there were significant NaNs in key demographic/chronic condition columns, we would address them here.
# Example: If BENE_SEX_IDENT_CD had NaNs, we could impute with the mode.

# 3. Identify categorical columns for encoding
# BENE_SEX_IDENT_CD, BENE_RACE_CD, BENE_ESRD_IND, SP_STATE_CODE, BENE_COUNTY_CD, Chronic condition flags (SP_...)
categorical_cols = ['BENE_SEX_IDENT_CD', 'BENE_RACE_CD', 'BENE_ESRD_IND', 'SP_STATE_CODE', 'BENE_COUNTY_CD']
# Add chronic condition columns - these are already encoded as 1 or 2, we might treat them as categorical or numerical.
# Let's treat them as categorical for now, but map 2 to 0 to represent absence.
chronic_condition_cols = [col for col in final_features_df.columns if col.startswith('SP_') and col != 'SP_STATE_CODE']
for col in chronic_condition_cols:
    final_features_df[col] = final_features_df[col].replace(2, 0)
    categorical_cols.append(col)

# Ensure selected categorical columns exist
categorical_cols = [col for col in categorical_cols if col in final_features_df.columns]

print("Categorical columns identified for encoding:", categorical_cols)

# Separate numerical columns for potential different preprocessing
numerical_cols = final_features_df.select_dtypes(include=np.number).columns.tolist()
# Remove the target variables and identifier from numerical columns
target_cols = ['had_readmit_30', 'had_readmit_60', 'had_readmit_90']
numerical_cols = [col for col in numerical_cols if col not in target_cols + ['DESYNPUF_ID']]
# Remove the categorical columns from numerical columns list
numerical_cols = [col for col in numerical_cols if col not in categorical_cols]


# Create preprocessing pipelines for numerical and categorical features
# Numerical pipeline: Impute with median (although we already imputed aggregated features with 0)
numerical_transformer = Pipeline(steps=[
    ('imputer', SimpleImputer(strategy='median')) # Median might be better for other numerical features if they had NaNs
])

# Categorical pipeline: Impute with a constant (e.g., 'missing') and then one-hot encode
categorical_transformer = Pipeline(steps=[
    ('imputer', SimpleImputer(strategy='constant', fill_value='missing')),
    ('onehot', OneHotEncoder(handle_unknown='ignore'))
])

# Create a column transformer to apply different transformations to different columns
preprocessor = ColumnTransformer(
    transformers=[
        ('num', numerical_transformer, numerical_cols),
        ('cat', categorical_transformer, categorical_cols)
    ],
    remainder='passthrough' # Keep other columns (like DESYNPUF_ID and target variables)
)

